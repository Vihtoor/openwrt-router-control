#!/bin/bash
awk 'NR<214 || NR>305 {print} NR==214 {
    print "        ImportKeyDialog(onDismiss = { showImportDialog = false }, onKeyImported = { id -> "
    print "            onSelectKey(id)"
    print "            showImportDialog = false"
    print "        })"
    print "    }"
    print ""
    print "    if (showGenerateDialog) {"
    print "        var newAlias by remember { mutableStateOf(\"My Key\") }"
    print "        var algorithm by remember { mutableStateOf(KeyPair.ED25519) }"
    print "        var passphrase by remember { mutableStateOf(\"\") }"
    print "        var isAlgorithmDropdownExpanded by remember { mutableStateOf(false) }"
    print ""
    print "        AlertDialog("
    print "            onDismissRequest = { if (!isGenerating) showGenerateDialog = false },"
    print "            title = { Text(translateText(\"Генерация SSH-ключа\", context)) },"
    print "            text = {"
    print "                Column {"
    print "                    OutlinedTextField("
    print "                        value = newAlias,"
    print "                        onValueChange = { newAlias = it },"
    print "                        label = { Text(translateText(\"Имя ключа\", context)) },"
    print "                        modifier = Modifier.fillMaxWidth(),"
    print "                        singleLine = true"
    print "                    )"
    print "                    Spacer(modifier = Modifier.height(8.dp))"
    print "                    "
    print "                    ExposedDropdownMenuBox("
    print "                        expanded = isAlgorithmDropdownExpanded,"
    print "                        onExpandedChange = { isAlgorithmDropdownExpanded = !isAlgorithmDropdownExpanded }"
    print "                    ) {"
    print "                        OutlinedTextField("
    print "                            value = if (algorithm == KeyPair.ED25519) \"ED25519\" else \"RSA 2048\","
    print "                            onValueChange = {},"
    print "                            readOnly = true,"
    print "                            label = { Text(translateText(\"Алгоритм\", context)) },"
    print "                            trailingIcon = { ExposedDropdownMenuDefaults.TrailingIcon(expanded = isAlgorithmDropdownExpanded) },"
    print "                            modifier = Modifier.menuAnchor().fillMaxWidth()"
    print "                        )"
    print "                        ExposedDropdownMenu("
    print "                            expanded = isAlgorithmDropdownExpanded,"
    print "                            onDismissRequest = { isAlgorithmDropdownExpanded = false }"
    print "                        ) {"
    print "                            DropdownMenuItem("
    print "                                text = { Text(\"ED25519 (Рекомендуется)\") },"
    print "                                onClick = { algorithm = KeyPair.ED25519; isAlgorithmDropdownExpanded = false }"
    print "                            )"
    print "                            DropdownMenuItem("
    print "                                text = { Text(\"RSA 2048\") },"
    print "                                onClick = { algorithm = KeyPair.RSA; isAlgorithmDropdownExpanded = false }"
    print "                            )"
    print "                        }"
    print "                    }"
    print "                    Spacer(modifier = Modifier.height(8.dp))"
    print "                    if (algorithm != KeyPair.ED25519) {"
    print "                        OutlinedTextField("
    print "                            value = passphrase,"
    print "                            onValueChange = { passphrase = it },"
    print "                            label = { Text(translateText(\"Пароль для ключа (опционально)\", context)) },"
    print "                            modifier = Modifier.fillMaxWidth(),"
    print "                            singleLine = true"
    print "                        )"
    print "                    }"
    print "                    Text("
    print "                        text = translateText(\"Генерация ключей производится в ОЗУ. Приватный ключ будет надежно зашифрован.\", context) +"
    print "                               if (algorithm == KeyPair.ED25519) \"\\n\\n\" + translateText(\"Примечание: для ED25519 пароль ключа не поддерживается\", context) else \"\","
    print "                        style = MaterialTheme.typography.bodySmall,"
    print "                        color = MaterialTheme.colorScheme.onSurfaceVariant,"
    print "                        modifier = Modifier.padding(top = 8.dp)"
    print "                    )"
    print "                }"
    print "            },"
    print "            confirmButton = {"
    print "                Button("
    print "                    onClick = {"
    print "                        isGenerating = true"
    print "                        coroutineScope.launch {"
    print "                            try {"
    print "                                val manager = SshKeyManager(context)"
    print "                                val entity = manager.generateAndSaveKey("
    print "                                    alias = newAlias,"
    print "                                    algorithm = algorithm,"
    print "                                    passphrase = passphrase.ifEmpty { null }"
    print "                                )"
    print "                                onSelectKey(entity.id)"
    print "                                showGenerateDialog = false"
    print "                            } catch (e: Throwable) {"
    print "                                e.printStackTrace()"
    print "                                Toast.makeText(context, \"Error: ${e.message ?: e.toString()}\", Toast.LENGTH_LONG).show()"
    print "                            } finally {"
    print "                                isGenerating = false"
    print "                            }"
    print "                        }"
    print "                    },"
    print "                    enabled = !isGenerating && newAlias.isNotBlank()"
    print "                ) {"
    print "                    if (isGenerating) {"
    print "                        CircularProgressIndicator(modifier = Modifier.size(24.dp), color = MaterialTheme.colorScheme.onPrimary)"
    print "                    } else {"
    print "                        Text(translateText(\"Сгенерировать\", context))"
    print "                    }"
    print "                }"
    print "            },"
    print "            dismissButton = {"
    print "                if (!isGenerating) {"
    print "                    TextButton(onClick = { showGenerateDialog = false }) {"
    print "                        Text(translateText(\"Отмена\", context))"
    print "                    }"
    print "                }"
    print "            }"
    print "        )"
    print "    }"
}' app/src/main/java/com/example/ui/SshKeyManagerDialog.kt > temp_dialog.kt
mv temp_dialog.kt app/src/main/java/com/example/ui/SshKeyManagerDialog.kt
